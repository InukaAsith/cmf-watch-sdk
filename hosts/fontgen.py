"""Bakes a TrueType font into sdk/cmf-wp2-ui/src/inter.rs for cmf_wp2_ui::font: 1-bit glyphs (the panel is
~350 ppi, so no blending is needed), each glyph as few rects as possible (runs of a row, merged down while the
next rows repeat them).

  uv run --with pillow python hosts/fontgen.py runs/font/Inter.ttf --size 20 --weight Medium

Inter: SIL Open Font License 1.1 (rsms.me/inter); embedding in an app is allowed.
"""
import argparse, pathlib

from PIL import Image, ImageDraw, ImageFont

OUT = pathlib.Path(__file__).resolve().parents[1] / "sdk/cmf-wp2-ui/src/inter.rs"
CHARS = "".join(sorted(set([chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x100)] + ["’", "“", "”", "…", "•"])))
# the cap top sits this many px below the y the caller gives (the old 16-px cells put caps at y + 2)
CAP_AT = 2


def rects(img):
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        runs, x = [], 0
        while x < w:
            if px[x, y]:
                s = x
                while x < w and px[x, y]:
                    x += 1
                runs.append((s, x - s))
            else:
                x += 1
        rows.append(runs)
    out = []
    used = [set() for _ in range(h)]
    for y in range(h):
        for r in rows[y]:
            if r in used[y]:
                continue
            k = 1
            while y + k < h and r in rows[y + k] and r not in used[y + k]:
                used[y + k].add(r)
                k += 1
            out.append((r[0], y, r[1], k))
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("ttf")
    p.add_argument("--size", type=int, default=20)
    p.add_argument("--weight", default="Medium")
    a = p.parse_args()
    f = ImageFont.truetype(a.ttf, a.size)
    f.set_variation_by_name(a.weight)
    cap_top = f.getbbox("H")[1]
    top = cap_top - CAP_AT  # font-image row that lands on the caller's y
    data, offs, advs, total = bytearray(), [0], [], 0
    for ch in CHARS:
        adv = round(f.getlength(ch))
        img = Image.new("1", (adv + 8, a.size * 2), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((2, 0), ch, font=f, fill=1)
        for x, y, w, h in rects(img):
            y -= top
            assert -128 <= y < 128 and w < 256 and h < 256 and x < 256, (ch, x, y, w, h)
            data += bytes([max(0, x - 2), y & 0xFF, w, h])  # y: i8, a few rows may sit above the cap
            total += 1
        offs.append(len(data) // 4)
        advs.append(adv)
    height = f.getbbox("Hgjy|")[3] - top
    src = [
        f"//! Generated by hosts/fontgen.py: {pathlib.Path(a.ttf).stem} {a.weight} {a.size} px, 1-bit. Do not edit.",
        "//! Inter: SIL Open Font License 1.1, Copyright (c) The Inter Project Authors.",
        "",
        f"/// Line box: rows below the given y that glyphs reach (descenders included).",
        f"pub const HEIGHT: i32 = {height};",
        f"pub static CODES: [u16; {len(CHARS)}] = {[ord(c) for c in CHARS]};",
        f"pub static ADV: [u8; {len(advs)}] = {advs};",
        f"pub static OFF: [u16; {len(offs)}] = {offs};",
        f"/// (x, y as i8, w, h) per rect.",
        f"pub static RECTS: [u8; {len(data)}] = {list(data)};",
        "",
    ]
    OUT.write_text("\n".join(l for l in src if l != "") + "\n")
    print(f"{OUT}: {len(CHARS)} glyphs, {total} rects ({total / len(CHARS):.1f}/glyph), {len(data)} B, height {height}")


if __name__ == "__main__":
    main()
